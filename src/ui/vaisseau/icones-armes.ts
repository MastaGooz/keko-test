/**
 * Les pixels d'une icône, contour compris : `[x, y, couleur]`, sur une grille de 14 × 14 (le dessin décalé d'un pixel,
 * pour que le contour tienne). Une arme sans icône n'en rend aucun.
 */
const DEJA = new Map<string, [number, number, string][]>()
export function pixelsDeLIcone(id: string): [number, number, string][] {
  const deja = DEJA.get(id)
  if (deja !== undefined) return deja
  const g = ICONES_DES_ARMES[id]
  const px: [number, number, string][] = []
  if (g !== undefined) {
    const plein = (x: number, y: number): boolean => y >= 0 && y < g.length && x >= 0 && x < g[y].length && g[y][x] !== '.'
    for (let y = -1; y <= 12; y++) {
      for (let x = -1; x <= 12; x++) {
        if (plein(x, y)) px.push([x + 1, y + 1, PALETTE[g[y][x]] ?? ENCRE_DES_ICONES])
        else if (plein(x - 1, y) || plein(x + 1, y) || plein(x, y - 1) || plein(x, y + 1)) px.push([x + 1, y + 1, ENCRE_DES_ICONES])
      }
    }
  }
  DEJA.set(id, px)
  return px
}
